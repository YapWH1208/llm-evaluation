from __future__ import annotations

from typing import Any, Protocol


class BenchmarkRepository(Protocol):
    def list_definitions(self) -> list[Any]: ...

    def get_definition(self, definition_id: str) -> Any | None: ...

    def find_definition(self, benchmark_id: str, version: str) -> Any | None: ...

    def create_definitions(self, values: list[dict[str, Any]]) -> list[Any] | None: ...

    def update_definition(
        self, definition_id: str, values: dict[str, Any], *, require_registered: bool
    ) -> Any | None: ...

    def find_dataset(self, dataset_id: str, version: str | None) -> Any | None: ...

    def create_prompt_package(self, values: dict[str, Any]) -> Any | None: ...

    def list_prompt_packages(self) -> list[Any]: ...

    def get_prompt_package(self, prompt_package_id: str) -> Any | None: ...

    def find_prompt_package(self, name: str, version: str) -> Any | None: ...

    def update_prompt_package(self, prompt_package_id: str, values: dict[str, Any]) -> Any | None: ...

    def delete_prompt_package(self, prompt_package_id: str) -> bool: ...

    def prompt_run_reference_exists(self, prompt_package_id: str) -> bool: ...

    def list_suites(self) -> list[Any]: ...
