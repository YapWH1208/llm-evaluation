from __future__ import annotations

from typing import Any, Protocol


class ReviewRepository(Protocol):
    def sample_attempt_exists(self, sample_attempt_id: str) -> bool: ...

    def create(self, values: dict[str, Any]) -> Any: ...

    def list_for_sample(self, sample_attempt_id: str) -> list[Any]: ...


class JudgeRepository(Protocol):
    def get_sample_attempt(self, sample_attempt_id: str) -> Any | None: ...

    def get_endpoint(self, endpoint_id: str) -> Any | None: ...

    def get_run(self, run_id: str) -> Any | None: ...

    def create_assessment(self, values: dict[str, Any]) -> Any: ...

    def update_assessment(self, assessment_id: str, values: dict[str, Any]) -> Any | None: ...

    def list_assessments(self, sample_attempt_id: str) -> list[Any]: ...
