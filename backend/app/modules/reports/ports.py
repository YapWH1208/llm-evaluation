from __future__ import annotations

from datetime import datetime, timedelta
from typing import Any, Protocol


class AssetRepository(Protocol):
    def find_by_digest(self, sha256: str) -> Any | None: ...

    def create_asset(self, values: dict[str, Any]) -> Any: ...

    def get_asset(self, asset_id: str) -> Any | None: ...


class ReportRepository(Protocol):
    def create_report(self, values: dict[str, Any]) -> Any: ...

    def get_report(self, report_id: str) -> Any | None: ...

    def list_reports(self, run_id: str) -> list[Any]: ...

    def delete_report(self, report_id: str) -> bool: ...

    def create_share(self, values: dict[str, Any]) -> Any: ...

    def get_share(self, share_id: str) -> Any | None: ...

    def find_share_by_token_hash(self, token_hash: str) -> Any | None: ...

    def list_shares(self, report_id: str) -> list[Any]: ...

    def update_share(self, share_id: str, values: dict[str, Any]) -> Any | None: ...

    def password_attempt_limit_reached(self, *, share_id: str, client_key: str, now: datetime, limit: int) -> bool: ...

    def record_password_failure(
        self, *, share_id: str, client_key: str, now: datetime, window: timedelta, limit: int
    ) -> None: ...
