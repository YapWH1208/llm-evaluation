from __future__ import annotations

from typing import Any, Protocol


class EndpointRepository(Protocol):
    def create(self, values: dict[str, Any]) -> Any: ...

    def list(self) -> list[Any]: ...

    def get(self, endpoint_id: str) -> Any | None: ...

    def update(self, endpoint_id: str, values: dict[str, Any]) -> Any | None: ...

    def delete(self, endpoint_id: str) -> bool: ...

    def list_capabilities(self, endpoint_id: str) -> list[Any]: ...

    def find_capability(self, endpoint_id: str, capability_key: str) -> Any | None: ...

    def upsert_capability(self, endpoint_id: str, capability_key: str, values: dict[str, Any]) -> Any: ...
